"""
Shiftwright shared contracts — v1.1 (see the "Changelog" in contracts/SEMANTICS.md).

OWNER: David. Every workstream builds against these models.
AGENTS: do NOT edit this file. If you need a change, write a request in
contracts/requests/<your-ws>-<short-name>.md (what, why, which fields) and stop
working on the dependent piece until David merges it.

Time conventions (read these, they prevent most bugs):
  * A schedule covers exactly one week. Store.week_start is always a MONDAY.
  * `day` is an int 0..6 (0 = Monday) relative to week_start.
  * Times are ints: minutes after local midnight of that day. Overnight shifts
    may have end > 1440 (e.g. 22:00-06:30 next day = 1320..1830).
  * Every start/end must be a multiple of Store.slot_minutes, EXCEPT (v1.1):
    Break.start/end, and RoleSegment.start/end where they touch a break, only
    need to be multiples of BREAK_GRANULARITY_MINUTES (5). Shift.start/end,
    DemandRequirement, Event and availability times stay on the slot grid.
  * Intervals are half-open: [start, end).
  * Money is USD floats rounded to cents at output; hours are floats.
  * Coverage and gap penalties are measured per minute (headcount-minutes / 60),
    so a 10-minute break leaves 10 minutes uncovered, not a whole slot.
    Gap.start/end are multiples of BREAK_GRANULARITY_MINUTES.

Metric and rule semantics the field docs leave open are fixed in
contracts/SEMANTICS.md (v1.1). Engine and validator must both follow it.
"""
from __future__ import annotations

from datetime import date, datetime
from enum import Enum
from typing import Any, Literal, Optional

from pydantic import BaseModel, Field

CONTRACT_VERSION = "1.1.0"
BREAK_GRANULARITY_MINUTES = 5


# --------------------------------------------------------------------------- #
# Shared enums
# --------------------------------------------------------------------------- #
class Strength(str, Enum):
    hard = "hard"   # never violated; if impossible -> infeasible / trade-off card
    soft = "soft"   # violation costs weight_dollars (per unit defined by kind)


class Source(str, Enum):
    law = "law"              # from the labor-law dataset; must carry a citation
    corporate = "corporate"  # corporate forecast / budget / policy
    leader = "leader"        # the store leader said so (chat or card)
    inferred = "inferred"    # mined from past schedules; provisional until confirmed
    employee = "employee"    # employee stated it (availability, preference)
    default = "default"      # template default; should be reviewed


class RuleStatus(str, Enum):
    provisional = "provisional"  # NOT used by the solver
    confirmed = "confirmed"      # used by the solver
    rejected = "rejected"        # kept for the audit trail, never used


class Citation(BaseModel):
    url: str
    title: str
    excerpt: str = Field(..., description="<=40 words quoted/paraphrased from source")
    last_verified: date


# --------------------------------------------------------------------------- #
# Store setup
# --------------------------------------------------------------------------- #
class Jurisdiction(BaseModel):
    state: str = Field(..., description="USPS code, e.g. 'TX'")
    city: Optional[str] = Field(None, description="Lowercase city name, e.g. 'seattle'")


class DayHours(BaseModel):
    day: int = Field(..., ge=0, le=6)
    open: int
    close: int  # may exceed 1440 for late-night stores


class Store(BaseModel):
    id: str
    name: str
    jurisdiction: Jurisdiction
    timezone: str = "America/Chicago"
    slot_minutes: Literal[15, 30, 60] = 30
    week_start: date
    hours: list[DayHours]
    pre_open_minutes: int = 60    # staff may work this long before open
    post_close_minutes: int = 60  # ...and after close
    school_week: Optional[bool] = Field(
        None,
        description=(
            "v1.1. Is the schedule week a school week for minors? None = unknown: enforce every "
            "matching minor_limits rule (strictest). True = only rules with school_week=true. "
            "False = only rules with school_week=false. See SEMANTICS.md #8."
        ),
    )


class Department(BaseModel):
    id: str    # e.g. "front_of_store"
    name: str  # e.g. "Front of Store"


class Role(BaseModel):
    id: str               # e.g. "cashier"
    department_id: str
    name: str
    min_age: int = 0      # e.g. 18 for pit_operator (federal hazardous-occupation rule)
    gap_penalty_per_hour: float = Field(
        ..., description="$ cost per headcount-hour left uncovered; encodes priority"
    )
    description: str = ""


class AvailabilityKind(str, Enum):
    unavailable = "unavailable"      # hard: never schedule inside this window
    preferred_off = "preferred_off"  # soft: penalty weight_dollars per hour scheduled inside
    preferred_on = "preferred_on"    # soft: penalty weight_dollars per hour NOT scheduled (rarely used)


class AvailabilityEntry(BaseModel):
    """Recurring weekly window (weekday set) or one-off (date set). Exactly one must be set."""
    weekday: Optional[int] = Field(None, ge=0, le=6)
    on_date: Optional[date] = None
    start: int
    end: int
    kind: AvailabilityKind
    weight_dollars: float = 0.0
    source: Source = Source.employee
    note: str = ""


class EmploymentStatus(str, Enum):
    full_time = "full_time"
    part_time = "part_time"
    seasonal = "seasonal"


class AttendanceStats(BaseModel):
    """Factual counts only. Used ONLY to rank call-in outreach. Never shown as a 'score'."""
    shifts_90d: int = 0
    callouts_90d: int = 0
    callins_offered_90d: int = 0
    callins_accepted_90d: int = 0


class Employee(BaseModel):
    id: str
    name: str
    phone: str = Field(..., description="E.164. Demo data uses fake numbers except the demo phones.")
    age: int
    home_department_id: str
    trained_role_ids: list[str] = Field(
        ..., description="HARD qualification gate. Untrained => never assigned to that role."
    )
    status: EmploymentStatus
    wage_per_hour: float
    min_hours_week: float = 0.0  # soft (weight from fairness constraint), see ConstraintKind.min_hours_week
    max_hours_week: float = 40.0  # hard
    availability: list[AvailabilityEntry] = []
    hire_date: date
    attendance: AttendanceStats = AttendanceStats()


class DemandSource(str, Enum):
    corporate = "corporate"  # imported corporate forecast
    leader = "leader"        # leader discretionary override
    event = "event"          # added because of an Event (truck, floor set...)


class DemandRequirement(BaseModel):
    """Need `headcount` people in `role_id` for every slot in [start, end) on `day`."""
    id: str
    role_id: str
    day: int = Field(..., ge=0, le=6)
    start: int
    end: int
    headcount: int = Field(..., ge=0)
    source: DemandSource
    event_id: Optional[str] = None
    note: str = ""


class EventKind(str, Enum):
    truck = "truck"
    floor_set = "floor_set"
    promo = "promo"
    online_surge = "online_surge"
    other = "other"


class Event(BaseModel):
    id: str
    kind: EventKind
    day: int = Field(..., ge=0, le=6)
    start: int
    end: int
    note: str = ""


class BudgetApproval(BaseModel):
    id: str
    extra_hours: float = 0.0
    extra_dollars: float = 0.0
    reason: str
    approved_by: str
    approved_at: datetime


class Budget(BaseModel):
    """Corporate sends HOURS. Hours cap is HARD unless raised by an approval."""
    weekly_hours_cap: float
    weekly_dollar_cap: Optional[float] = None  # hard if set
    overtime_allowed: bool = False             # if False, nobody exceeds OT thresholds
    approvals: list[BudgetApproval] = []


# --------------------------------------------------------------------------- #
# Rules / constraints
# --------------------------------------------------------------------------- #
class ConstraintKind(str, Enum):
    """
    The COMPLETE set of rules the engine understands. Anything else a leader says
    goes to StoreConfig.unmodeled. params schema per kind:

    min_shift_length         {minutes:int}
    max_shift_length         {minutes:int}
    min_rest_between_shifts  {minutes:int}                         # anti-"clopen"
    max_days_per_week        {days:int}
    max_consecutive_days     {days:int}
    min_hours_week           {}  (uses Employee.min_hours_week; soft; weight = $/hour short)
    not_together             {employee_ids:[a,b]}                  # no overlapping shifts; soft weight = $/overlapping hour
    fair_spread              {shift_class:"open"|"close"|"weekend", max_per_employee:int}
                             # open = starts before store open; close = ends after store close
                             # soft weight = $ per excess occurrence
    always_staffed           {role_id:str, windows:"store_hours"|"staff_hours"}
                             # e.g. leader_on_duty must be covered whenever open
    preferred_role           {employee_id:str, role_id:str}        # soft weight = $/hour NOT in that role
    week_stability           {}  (soft weight = $/hour changed vs previous_schedule; optional)

    `applies_to_employee_ids` = None means everyone.
    """
    min_shift_length = "min_shift_length"
    max_shift_length = "max_shift_length"
    min_rest_between_shifts = "min_rest_between_shifts"
    max_days_per_week = "max_days_per_week"
    max_consecutive_days = "max_consecutive_days"
    min_hours_week = "min_hours_week"
    not_together = "not_together"
    fair_spread = "fair_spread"
    always_staffed = "always_staffed"
    preferred_role = "preferred_role"
    week_stability = "week_stability"


class Constraint(BaseModel):
    id: str
    kind: ConstraintKind
    params: dict[str, Any] = {}
    strength: Strength
    weight_dollars: float = 0.0  # required > 0 when strength == soft
    applies_to_employee_ids: Optional[list[str]] = None
    source: Source
    status: RuleStatus
    citation: Optional[Citation] = None  # required when source == law
    evidence: Optional[str] = None       # required when source == inferred, e.g. "8/8 weeks had >=2 cashiers after 17:00"
    note: str = ""                       # human-readable statement shown in the rulebook


class UnmodeledNote(BaseModel):
    """Something the leader said that no ConstraintKind can express. Shown in the rulebook."""
    id: str
    text: str
    reason: str
    created_at: datetime


# --------------------------------------------------------------------------- #
# Labor law dataset
# --------------------------------------------------------------------------- #
class LawRuleType(str, Enum):
    """
    params schema per type (all minutes unless noted):

    weekly_overtime          {threshold_hours:float, multiplier:float}
    daily_overtime           {threshold_hours:float, multiplier:float,
                              double_threshold_hours:float|null}
    meal_break               {after_minutes:int, duration:int, paid:bool,
                              latest_start_minute_of_shift:int|null, waivable_under_minutes:int|null}
    rest_break               {per_minutes_worked:int, duration:int, paid:bool}
    minor_limits             {age_min:int, age_max:int, school_week:bool,
                              max_hours_day:float|null, max_hours_week:float|null,
                              earliest_start:int|null, latest_end:int|null,
                              latest_end_summer:int|null}
    minor_prohibited_roles   {age_below:int, role_tags:[str]}   # e.g. 18, ["powered_industrial_truck"]
    min_rest_between_shifts  {minutes:int, premium_multiplier:float|null, waivable:bool}
    predictive_scheduling    {notice_days:int, change_premium_hours:float,
                              applies_if_employees_over:int|null, applies_to:"retail"|"food"|"both"}
    reporting_time_pay       {min_paid_hours:float|null, fraction_of_scheduled:float|null}
    minimum_wage             {dollars_per_hour:float, effective:date}
    """
    weekly_overtime = "weekly_overtime"
    daily_overtime = "daily_overtime"
    meal_break = "meal_break"
    rest_break = "rest_break"
    minor_limits = "minor_limits"
    minor_prohibited_roles = "minor_prohibited_roles"
    min_rest_between_shifts = "min_rest_between_shifts"
    predictive_scheduling = "predictive_scheduling"
    reporting_time_pay = "reporting_time_pay"
    minimum_wage = "minimum_wage"


class LawRule(BaseModel):
    id: str  # e.g. "CA.meal_break.1"
    jurisdiction: Jurisdiction
    level: Literal["federal", "state", "city"]
    type: LawRuleType
    params: dict[str, Any]
    summary: str  # one plain-English sentence
    citation: Citation
    confidence: Literal["high", "medium", "low"]
    verified: bool = False  # set True only by the verifier agent / a human


class LawPack(BaseModel):
    """Resolved rules for one store: federal + state + city, most-protective wins."""
    jurisdiction: Jurisdiction
    rules: list[LawRule]
    coverage: Literal["full", "state_only", "federal_fallback"]
    warnings: list[str] = []  # e.g. "No dataset entry for city 'round rock'; state + federal applied."


# --------------------------------------------------------------------------- #
# The config
# --------------------------------------------------------------------------- #
class StoreConfig(BaseModel):
    contract_version: str = CONTRACT_VERSION
    config_version: int = 1  # bump on every mutation
    store: Store
    departments: list[Department]
    roles: list[Role]
    role_tags: dict[str, list[str]] = Field(
        default_factory=dict, description="role_id -> tags, e.g. pit_operator -> ['powered_industrial_truck']"
    )
    employees: list[Employee]
    demand: list[DemandRequirement]
    events: list[Event] = []
    budget: Budget
    constraints: list[Constraint] = []
    unmodeled: list[UnmodeledNote] = []
    law_pack: Optional[LawPack] = None  # filled by api from data/laws at solve time


