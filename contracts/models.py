class Break(BaseModel):
    start: int
    end: int
    kind: Literal["meal", "rest"]
    paid: bool


class RoleSegment(BaseModel):
    role_id: str
    start: int
    end: int


class Shift(BaseModel):
    id: str
    employee_id: str
    day: int = Field(..., ge=0, le=6)
    start: int
    end: int
    breaks: list[Break] = []
    segments: list[RoleSegment] = Field(
        ..., description="Cover [start,end) minus breaks exactly, no overlaps. Mid-shift role changes allowed."
    )


class GapReasonCode(str, Enum):
    not_trained = "not_trained"
    unavailable = "unavailable"
    at_max_hours = "at_max_hours"
    budget_cap = "budget_cap"
    law_rule = "law_rule"
    minor_rule = "minor_rule"
    rest_rule = "rest_rule"
    already_assigned = "already_assigned"  # working a higher-priority role at that time
    cheaper_to_leave_gap = "cheaper_to_leave_gap"


class GapReason(BaseModel):
    employee_id: str
    code: GapReasonCode
    constraint_id: Optional[str] = None
    law_rule_id: Optional[str] = None


class Gap(BaseModel):
    role_id: str
    day: int
    start: int
    end: int
    missing_headcount: int
    penalty_dollars: float
    reasons: list[GapReason] = Field(
        default_factory=list,
        description="One per employee TRAINED for the role: why they are not covering it.",
    )


class SoftViolation(BaseModel):
    constraint_id: Optional[str] = None
    kind: str  # ConstraintKind value or "availability_preference"
    employee_id: Optional[str] = None
    amount: float  # hours / occurrences, per kind
    penalty_dollars: float
    note: str = ""


class ScheduleMetrics(BaseModel):
    total_hours: float
    total_wage_cost: float
    overtime_hours: float
    premium_pay_dollars: float = 0.0   # law premiums (clopen, predictive scheduling...)
    coverage_pct: float                # 0-100: covered headcount-hours / required headcount-hours
    gap_penalty_dollars: float
    soft_penalty_dollars: float
    objective_dollars: float           # wage + premiums + gap + soft penalties
    budget_hours_cap: float
    budget_hours_used: float


class Infeasibility(BaseModel):
    """Only when HARD constraints conflict (gaps never cause infeasibility; they are priced)."""
    conflicting_constraint_ids: list[str] = []
    conflicting_law_rule_ids: list[str] = []
    conflicting_other: list[str] = []  # e.g. "budget.weekly_hours_cap", "employee:e12.max_hours_week"
    summary: str


class Schedule(BaseModel):
    store_id: str
    week_start: date
    config_version: int
    produced_by: str  # "engine", "baseline:grok", "baseline:raw-claude", ...
    status: Literal["optimal", "feasible", "infeasible", "error"]
    shifts: list[Shift] = []
    gaps: list[Gap] = []
    soft_violations: list[SoftViolation] = []
    metrics: Optional[ScheduleMetrics] = None
    infeasibility: Optional[Infeasibility] = None
    solver_stats: dict[str, Any] = {}


